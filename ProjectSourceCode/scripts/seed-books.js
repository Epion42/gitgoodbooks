// Generates init-data/03-books.sql from Google Books.
// Run from ProjectSourceCode/:  node scripts/seed-books.js
require("dotenv").config();
const fs = require("fs");
const path = require("path");
const axios = require("axios");
const pgp = require("pg-promise")(); // only used for SQL escaping; never connects
const { normalizeVolume } = require("../booksApi");

// Names must match how Google labels categories (BISAC), e.g. "Fiction / Science Fiction"
const GENRES = [
  { name: "Fantasy", slug: "fantasy" },
  { name: "Science Fiction", slug: "science-fiction" },
  { name: "Mystery & Detective", slug: "mystery" },
  { name: "Thrillers", slug: "thrillers" },
  { name: "Romance", slug: "romance" },
  { name: "Horror", slug: "horror" },
  { name: "Historical", slug: "historical-fiction" },
  { name: "Young Adult Fiction", slug: "young-adult" },
  { name: "Biography & Autobiography", slug: "biography" },
  { name: "History", slug: "history" },
  { name: "Self-Help", slug: "self-help" },
];

const PAGES_PER_GENRE = 3;
const PAGE_SIZE = 40; // Google's max
const OUT_FILE = path.join(__dirname, "../init-data/03-books.sql");

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fetchGenre(genre) {
  const books = [];
  for (let page = 0; page < PAGES_PER_GENRE; page++) {
    const { data } = await axios.get(
      "https://www.googleapis.com/books/v1/volumes",
      {
        params: {
          q: `subject:"${genre.name}"`,
          startIndex: page * PAGE_SIZE,
          maxResults: PAGE_SIZE,
          printType: "books",
          langRestrict: "en",
          key: process.env.API_KEY,
        },
        timeout: 10000,
      },
    );
    books.push(...(data.items ?? []).map(normalizeVolume));
    await sleep(500); // be polite to the API
  }
  return books;
}

// Skip books that would look broken on browse or violate table constraints
function isUsable(book) {
  return (
    book.thumbnail &&
    book.description &&
    book.authors.length > 0 &&
    book.publishYear > 0 &&
    book.publishYear < 2050 &&
    book.link &&
    book.link.length <= 256
  );
}

// "Dune: Deluxe Edition" by Frank Herbert and "Dune" by Frank Herbert -> same key
function editionKey(book) {
  const title = book.title
    .toLowerCase()
    .split(":")[0]
    .replace(/[^a-z0-9 ]/g, "")
    .trim();
  return `${title}|${book.authors[0].toLowerCase()}`;
}

function toSql(books) {
  const lines = [
    "-- Generated by scripts/seed-books.js, do not edit by hand",
    "",
  ];

  for (const genre of GENRES) {
    lines.push(
      pgp.as.format(
        `INSERT INTO category (categoryName, slug) VALUES ($1, $2)
         ON CONFLICT (categoryName) DO UPDATE SET slug = EXCLUDED.slug;`,
        [genre.name, genre.slug],
      ),
    );
  }

  for (const book of books) {
    lines.push(
      pgp.as.format(
        `INSERT INTO books (bookId, bookTitle, authors, publishDate, description, thumbnail, pageCount, bookLink)
         VALUES ($1, $2, $3, $4, $5, $6, $7, $8) ON CONFLICT (bookId) DO NOTHING;`,
        [
          book.bookId,
          book.title,
          book.authors,
          book.publishYear,
          book.description,
          book.thumbnail,
          book.pageCount,
          book.link,
        ],
      ),
    );
    for (const name of book.categories) {
      const category = name.slice(0, 64);
      lines.push(
        pgp.as.format(
          "INSERT INTO category (categoryName) VALUES ($1) ON CONFLICT DO NOTHING;",
          [category],
        ),
        // Look the id up by name so we never depend on SERIAL ids lining up
        pgp.as.format(
          `INSERT INTO bookToCategory (bookId, categoryId)
           SELECT $1, categoryId FROM category WHERE categoryName = $2
           ON CONFLICT DO NOTHING;`,
          [book.bookId, category],
        ),
      );
    }
  }

  return lines.join("\n") + "\n";
}

async function main() {
  if (!process.env.API_KEY) throw new Error("API_KEY is not set in .env");

  const byEdition = new Map();
  for (const genre of GENRES) {
    const usable = (await fetchGenre(genre)).filter(isUsable);
    for (const book of usable) {
      const key = editionKey(book);
      const kept = byEdition.get(key) ?? book;
      // Google doesn't always list the subject we searched for, so add it
      kept.categories = [...new Set([...kept.categories, genre.name])];
      byEdition.set(key, kept);
    }
    console.log(`${genre.name}: ${usable.length} usable`);
  }

  const books = [...byEdition.values()];
  fs.writeFileSync(OUT_FILE, toSql(books));
  console.log(`Wrote ${books.length} books to ${OUT_FILE}`);
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
